// Export the repository's MySQL model and static defaults without starting the app.
// Run with Node 24+: node database/supabase/generate.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, resolve } from 'node:path';
import { stripTypeScriptTypes } from 'node:module';
import { runInNewContext } from 'node:vm';

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, '../..');
const read = p => readFileSync(resolve(root, p), 'utf8');
const quote = s => `"${s.replaceAll('"', '""')}"`;
const literal = v => v == null ? 'NULL' : typeof v === 'number' ? String(v) : `'${String(v).replaceAll("'", "''")}'`;

function splitTop(s) {
  const parts = [];
  let start = 0, depth = 0, quoted = false;
  for (let i = 0; i < s.length; i++) {
    if (s[i] === "'") {
      if (quoted && s[i + 1] === "'") { i++; continue; }
      quoted = !quoted;
    }
    if (quoted) continue;
    if (s[i] === '(') depth++;
    if (s[i] === ')') depth--;
    if (s[i] === ',' && depth === 0) { parts.push(s.slice(start, i).trim()); start = i + 1; }
  }
  parts.push(s.slice(start).trim());
  return parts;
}
const columns = s => splitTop(s).map(x => {
  const prefix = /^(\w+)\((\d+)\)$/.exec(x);
  return prefix ? `left(${quote(prefix[1])}, ${prefix[2]})` : quote(x.replaceAll('`', ''));
}).join(', ');

const source = read('server/src/schema.sql').replace(/^\s*--.*$/gm, '');
const tables = [], indexes = [], security = [], manifest = [];
for (const match of source.matchAll(/CREATE TABLE IF NOT EXISTS (\w+)\s*\(([\s\S]*?)\);/g)) {
  const [, table, body] = match;
  const definitions = [], fields = [], foreignKeys = [], covered = [];
  let indexNumber = 0;
  const index = (list, unique = false, label) => {
    const name = label ? `${table}_${label}` : `${table}_${++indexNumber}_idx`;
    indexes.push(`CREATE ${unique ? 'UNIQUE ' : ''}INDEX ${quote(name)} ON public.${quote(table)} (${columns(list)});`);
    covered.push(list.replaceAll('`', '').split(',')[0].trim());
  };
  for (let definition of splitTop(body)) {
    if (/^INDEX\s*\(/i.test(definition)) { index(definition.match(/\(([\s\S]*)\)$/)[1]); continue; }
    if (/^UNIQUE KEY\b/i.test(definition)) {
      const m = /^UNIQUE KEY\s*(\w+)?\s*\(([\s\S]*)\)$/i.exec(definition);
      index(m[2], true, m[1]); continue;
    }
    if (/^PRIMARY KEY/i.test(definition)) {
      const list = definition.match(/\((.*)\)/)[1];
      covered.push(list.split(',')[0].trim());
      definitions.push(`PRIMARY KEY (${columns(list)})`); continue;
    }
    if (/^FOREIGN KEY/i.test(definition)) {
      const m = /^FOREIGN KEY\s*\((\w+)\) REFERENCES (\w+)\((\w+)\)(.*)$/i.exec(definition);
      if (!m) throw new Error(`Unsupported foreign key: ${definition}`);
      foreignKeys.push(m[1]);
      definitions.push(`FOREIGN KEY (${quote(m[1])}) REFERENCES public.${quote(m[2])} (${quote(m[3])})${m[4]}`); continue;
    }
    const m = /^`?(\w+)`?\s+([\s\S]+)$/.exec(definition);
    if (!m) throw new Error(`Unsupported definition: ${definition}`);
    const [, field] = m;
    let type = m[2], check = '';
    const enumeration = /ENUM\(([^)]*)\)/i.exec(type);
    if (enumeration) {
      type = type.replace(enumeration[0], 'TEXT');
      check = ` CHECK (${quote(field)} IN (${enumeration[1]}))`;
    }
    if (/TINYINT\(1\)/i.test(type)) {
      type = type.replace(/TINYINT\(1\)/ig, 'SMALLINT');
      check = ` CHECK (${quote(field)} IN (0, 1))`;
    }
    type = type.replace(/\bDATETIME\b/ig, 'TIMESTAMPTZ')
      .replace(/\bMEDIUMTEXT\b/ig, 'TEXT').replace(/\bJSON\b/ig, 'JSONB')
      .replace(/\bAUTO_INCREMENT\b/ig, 'GENERATED BY DEFAULT AS IDENTITY');
    if (/PRIMARY KEY|UNIQUE/i.test(type)) covered.push(field);
    fields.push({ name: field, identity: /IDENTITY/.test(type), type });
    definitions.push(`${quote(field)} ${type}${check}`);
  }
  for (const fk of foreignKeys) if (!covered.includes(fk)) index(fk, false, `${fk}_fk_idx`);
  tables.push(`CREATE TABLE public.${quote(table)} (\n  ${definitions.join(',\n  ')}\n);`);
  security.push(`ALTER TABLE public.${quote(table)} ENABLE ROW LEVEL SECURITY;`,
    `REVOKE ALL ON TABLE public.${quote(table)} FROM PUBLIC, anon, authenticated;`);
  for (const field of fields.filter(f => f.identity)) {
    security.push(`REVOKE ALL ON SEQUENCE public.${quote(`${table}_${field.name}_seq`)} FROM PUBLIC, anon, authenticated;`);
  }
  manifest.push({ table, columns: fields.map(f => f.name), foreignKeys: foreignKeys.length });
}
if (tables.length !== 64) throw new Error(`Expected 64 tables, found ${tables.length}`);
if (source.replace(/CREATE TABLE IF NOT EXISTS (\w+)\s*\(([\s\S]*?)\);/g, '').trim()) throw new Error('Unparsed schema statements');
writeFileSync(resolve(here, 'schema.sql'), `-- Generated from server/src/schema.sql. Fresh destination only.\n-- All MySQL DATETIME values represent UTC. Import historical timestamps with UTC timezone.\n-- Custom application sessions are preserved; they are not Supabase Auth sessions.\n-- Browser access is closed until an authorization model has been implemented.\nBEGIN;\nSET LOCAL TIME ZONE 'UTC';\n\n${tables.join('\n\n')}\n\n${indexes.join('\n')}\n\n${security.join('\n')}\nCOMMIT;\n`);

// Evaluate only the static seed definitions, with no imports or application side effects.
function constants(text, names) {
  const js = stripTypeScriptTypes(text.replace(/^import .*;\r?\n/gm, '').replace(/\bexport /g, ''));
  return runInNewContext(`${js}\n;({${names.join(',')}})`, {}, { timeout: 1000 });
}
const { BUILTIN_ROLES } = constants(read('server/src/perms.ts'), ['BUILTIN_ROLES']);
const seed = read('server/src/seed.ts');
const { SYSTEM, OTHER, CITIES } = constants(seed.slice(0, seed.indexOf('const WIDENED:')), ['SYSTEM', 'OTHER', 'CITIES']);
const mail = read('server/src/mail.ts');
const { SEED } = constants(mail.slice(0, mail.indexOf('export async function seedTemplates')), ['SEED']);
const statements = [];
function insert(table, fields, rows, conflict) {
  statements.push(`INSERT INTO public.${quote(table)} (${fields.map(quote).join(', ')}) VALUES\n${rows.map(row => `  (${row.map(literal).join(', ')})`).join(',\n')}\nON CONFLICT (${fields.slice(0, conflict).map(quote).join(', ')}) DO NOTHING;`);
}
insert('settings', ['key', 'value', 'type', 'category', 'description', 'editable'], [
  ...SYSTEM.map(([k,v,t,c,d]) => [k,v,t,c,d,1]), ...OTHER.map(([k,v,c]) => [k,v,'text',c,null,0]),
], 1);
insert('roles', ['name', 'description'], BUILTIN_ROLES.map(r => [r.name, r.description]), 1);
for (const role of BUILTIN_ROLES) {
  statements.push(`INSERT INTO public.role_permissions (role_id, perm)\nSELECT r.id, p.perm FROM public.roles r CROSS JOIN (VALUES\n${[...new Set(role.perms)].map(p => `  (${literal(p)})`).join(',\n')}\n) AS p(perm) WHERE r.name = ${literal(role.name)}\nON CONFLICT (role_id, perm) DO NOTHING;`);
}
insert('cities', ['name_ar', 'name_en'], CITIES, 1);
insert('email_templates', ['tkey','name','subject','body_html','placeholders','grp','is_system','is_required'], SEED.map(t => [t.key,t.name,t.subject,t.body,t.placeholders,t.grp,1,t.required]), 1);
writeFileSync(resolve(here, 'seed.sql'), `-- Repository defaults only; no admin account, passwords or operational records.\n-- system.installed stays 0 until the PostgreSQL application setup is ready.\nBEGIN;\nSET LOCAL TIME ZONE 'UTC';\n${statements.join('\n\n')}\nCOMMIT;\n`);
writeFileSync(resolve(here, 'manifest.json'), JSON.stringify({ tables: manifest, defaults: { settings: SYSTEM.length + OTHER.length, roles: BUILTIN_ROLES.length, rolePermissions: BUILTIN_ROLES.reduce((n,r) => n + new Set(r.perms).size, 0), cities: CITIES.length, emailTemplates: SEED.length } }, null, 2) + '\n');
console.log(`Generated ${tables.length} tables and ${indexes.length} indexes, with repository defaults.`);
